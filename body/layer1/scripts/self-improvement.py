def _init_improvements_file(path: Path) -> None:
    if path.exists():
        return
    _safe_write_text(path, _IMPROVEMENTS_TEMPLATE)


def _append_to_section(improvements_file: Path, section: str, content: str) -> bool:
    """Append content after section header's HTML comment line."""
    text = _read_text(improvements_file)
    if not text:
        return False

    lines = text.split("\n")
    output = []
    in_section = False
    appended = False
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M")

    for line in lines:
        output.append(line)
        if section in line and (line.startswith("###") or line.startswith("##")):
            in_section = True
        elif in_section and line.strip().startswith("<!--") and not appended:
            output.append("")
            output.append(f"#### {timestamp} - {section}")
            output.append("")
            output.append(content)
            output.append("")
            appended = True
            in_section = False
        elif line.startswith("---") or line.startswith("##"):
            in_section = False

    if appended:
        _safe_write_text(improvements_file, "\n".join(output))
        return True
    return False


