#!/usr/bin/env python3
"""Native incremental self-improvement tracker for findings/leads.

Derives value from new findings/leads as they're documented.
Invariant: Append-only to IMPROVEMENTS.md; proposals only, no auto-modifications.

Unlike growth.py (which runs once at engagement end), this runs:
  - After new findings/leads are documented
"""

from __future__ import annotations

import argparse
import hashlib
import re
from datetime import UTC, datetime
import json
from pathlib import Path
import tempfile
import sys


FINDING_RE = re.compile(r"^##\s*\[FINDING-", re.MULTILINE)
LEAD_RE = re.compile(r"^###\s*\[[A-Z-]+\]", re.MULTILINE)
CWE_RE = re.compile(r"CWE-\d+")
ATTACK_TYPE_RE = re.compile(
    r"\b(injection|XSS|CSRF|overflow|bypass|traversal|SSRF|XXE|RCE|LFI|RFI|IDOR|deserialization)\b",
    re.IGNORECASE,
)


def _utc_now() -> str:
    return datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def _today() -> str:
    return datetime.now().strftime("%Y-%m-%d")


def _find_body_root(script_path: Path) -> Path:
    script_root = script_path.resolve().parents[2]
    for candidate in (Path.cwd().resolve(), script_root):
        if (candidate / ".bra").exists() or (candidate / "layer3-engagement").exists():
            return candidate
    return script_root


def _append_log(log_file: Path, level: str, message: str) -> None:
    log_file.parent.mkdir(parents=True, exist_ok=True)
    with log_file.open("a", encoding="utf-8") as handle:
        handle.write(f"[{_utc_now()}] [{level}] {message}\n")


def _safe_write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent, prefix=path.name + ".", delete=False) as tmp:
        tmp.write(content)
        temp_path = Path(tmp.name)
    temp_path.replace(path)


def _safe_write_json(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent, prefix=path.name + ".", delete=False) as tmp:
        json.dump(payload, tmp, indent=2)
        tmp.write("\n")
        temp_path = Path(tmp.name)
    temp_path.replace(path)


def _read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def _dir_hash(directory: Path) -> str:
    """Hash all files in directory for change detection."""
    if not directory.is_dir():
        return ""
    h = hashlib.sha256()
    for f in sorted(directory.rglob("*")):
        if f.is_file():
            try:
                h.update(f.read_bytes())
            except OSError:
                pass
    return h.hexdigest()


# ============== STATE ==============

_DEFAULT_STATE = {
    "last_findings_count": 0,
    "last_leads_count": 0,
    "last_intel_hash": "",
    "last_static_hash": "",
    "last_dynamic_hash": "",
    "last_report_hash": "",
    "pending_improvements": 0,
    "improvement_counter": 0,
    "timestamp": "",
}


def _load_state(path: Path) -> dict:
    default = dict(_DEFAULT_STATE)
    default["timestamp"] = _utc_now()
    if not path.is_file():
        return default
    try:
        data = json.loads(path.read_text(encoding="utf-8", errors="replace"))
    except json.JSONDecodeError:
        return default
    for key, value in default.items():
        data.setdefault(key, value)
    return data


