# ============== MAIN ==============

def main(argv: list[str] | None = None) -> int:
    _HELP_TEXT = """\
self-improvement.py — Incremental Self-Improvement Engine

USAGE:
    self-improvement.py --finding        Analyze latest finding(s)
    self-improvement.py --lead           Analyze latest lead(s)
    self-improvement.py --overrides      Analyze override usage patterns
    self-improvement.py --status         Show pending improvements
    self-improvement.py --promote        Implement approved [x] items from pitch docs
    self-improvement.py --promote-overrides  Promote approved override pitches; delete denied
    self-improvement.py --dry-run        Preview what --promote would do
    self-improvement.py --help           Show this help

DESCRIPTION:
    Runs when new findings or leads are added to layer3-engagement/NOTES/. Use growth.py
    at engagement end for full-retro proposals.

AUTO-INVOCATION:
    This script is automatically invoked by:
    - notes_guard.py after FINDINGS.md or LEADS.md is appended

DATA SOURCES:
    --finding  layer3-engagement/NOTES/FINDINGS.md (latest)  Attack patterns, CWEs
    --lead     layer3-engagement/NOTES/LEADS.md (latest)     Attack surface ideas

OUTPUT:
    layer3-engagement/IMPROVEMENTS.md            Rolling improvement log (append-only)
    layer3-engagement/pitches/YYYY-MM-DD-*.md    Pitch documents for review

PROMOTION WORKFLOW:
    1. Review pitch documents in GUI or directly in layer3-engagement/pitches/
    2. Mark approved items with [x] checkbox
    3. Run: ./self-improvement.py --promote
    4. Approved items are implemented into Layer 2 templates:
       - Skills → layer2-templates/skillset.md
       - Tools → layer2-templates/toolset.md
       - Methodologies → layer2-templates/methodologies/
       - Attack Chains → layer2-templates/attack-chains/

IMPROVEMENT CATEGORIES:
    - Skills: New skills based on techniques used
    - Methodologies: Template updates
    - Attack Chains: Reusable attack sequences
    - Attack Surface: New scope/intel areas (manual)
    - Tools: Tool additions/configurations

EXIT CODES:
    0 - Success (improvements logged)
    1 - Error (write failure)
    2 - No new data (unchanged since last analysis)

EXAMPLES:
    # Check status of pending improvements
    ./self-improvement.py --status

    # Analyze latest finding
    ./self-improvement.py --finding

    # Analyze latest lead
    ./self-improvement.py --lead

    # Preview what would be promoted
    ./self-improvement.py --dry-run

    # Implement approved proposals into templates
    ./self-improvement.py --promote

    # Promote approved override recommendations to layer2 template and delete denied entries
    ./self-improvement.py --promote-overrides

REFERENCED BY:
    - layer1/scripts/notes_guard.py (auto-invoke after finding/lead append)
    - Manual operator invocation
    - BRA GUI (Growth page)

SEE ALSO:
    - growth.py (full engagement analysis, runs once at end)
    - lessons-learned.py (engagement narrative)
"""
    parser = argparse.ArgumentParser(
        description="Analyze new findings/leads and track incremental improvements.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=_HELP_TEXT,
    )
    parser.add_argument("--finding", action="store_true", help="Analyze newly added findings")
    parser.add_argument("--lead", action="store_true", help="Analyze newly added leads")
    parser.add_argument("--overrides", action="store_true", help="Analyze override usage patterns")
    parser.add_argument("--status", "-s", action="store_true", help="Show status")
    parser.add_argument("--promote", "-p", action="store_true", help="Promote approved checklist items from pitch docs")
    parser.add_argument("--promote-overrides", action="store_true", help="Promote approved override checklist items")
    parser.add_argument("--ingest-overrides", action="store_true", help="Alias for --promote-overrides")
    parser.add_argument("--dry-run", action="store_true", help="Preview promotion actions")
    parser.add_argument("--auto", action="store_true", help="Suppress user prompts (for auto-invocation)")
    args = parser.parse_args(sys.argv[1:] if argv is None else argv)

    body_root = _find_body_root(Path(__file__))
    notes_dir = body_root / "layer3-engagement" / "NOTES"
    pitches_dir = body_root / "layer3-engagement" / "pitches"
    improvements_file = body_root / "layer3-engagement" / "IMPROVEMENTS.md"
    state_file = body_root / ".bra" / "improvement_state.json"
    log_file = body_root / ".bra" / "logs" / "self_improvement.log"

    _init_improvements_file(improvements_file)
    state = _load_state(state_file)

    if args.ingest_overrides:
        args.promote_overrides = True

    if args.dry_run and not args.promote and not args.promote_overrides:
        rc = _promote(body_root, state, improvements_file, pitches_dir, log_file, True)
        _safe_write_json(state_file, state)
        return rc

    if not any((args.finding, args.lead, args.overrides, args.promote, args.promote_overrides, args.status, args.dry_run)):
        print(parser.format_help(), end="")
        return 0

    if args.status:
        return _status(state, pitches_dir)

    if args.overrides:
        rc = _analyze_overrides(body_root, state, pitches_dir, log_file)
        _safe_write_json(state_file, state)
        return rc

    if args.promote or args.promote_overrides:
        if args.promote_overrides:
            rc = _promote_overrides(body_root, state, pitches_dir, log_file)
        else:
            rc = _promote(body_root, state, improvements_file, pitches_dir, log_file, args.dry_run)
        _safe_write_json(state_file, state)
        return rc

    rc = 0
    if args.finding:
        rc = _analyze_finding(body_root, state, improvements_file, pitches_dir, log_file)

    if args.lead:
        rc2 = _analyze_lead(body_root, state, improvements_file, pitches_dir, log_file)
        if rc == 0:
            rc = rc2

    _safe_write_json(state_file, state)
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
