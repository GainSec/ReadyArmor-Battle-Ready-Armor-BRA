def _maybe_generate_pitch(body_root: Path, source: str, content: str, state: dict,
                          pitches_dir: Path, findings_text: str, leads_text: str) -> Path | None:
    """Generate pitch if 3+ proposals."""
    proposal_count = content.count("- [ ]")
    if proposal_count < 3:
        return None
    counter = int(state.get("improvement_counter", 0)) + 1
    state["improvement_counter"] = counter
    return _create_pitch(pitches_dir, source, proposal_count, content,
                         findings_text, leads_text, counter)


# ============== ATTACK PATTERN EXTRACTION ==============

def _extract_attack_patterns(text: str) -> str:
    """Extract CWEs and attack types from finding text."""
    cwes = sorted(set(CWE_RE.findall(text)))
    attacks = sorted(set(ATTACK_TYPE_RE.findall(text)))
    parts = []
    if cwes:
        parts.append(f"CWEs: {', '.join(cwes)}")
    if attacks:
        parts.append(f"Attack Types: {', '.join(attacks)}")
    return "\n".join(parts)


# ============== PHASE ARTIFACT ANALYSIS ==============

def _analyze_phase_artifacts(body_root: Path, phase: str, state: dict,
                             improvements_file: Path, pitches_dir: Path,
                             findings_text: str, leads_text: str, log_file: Path) -> bool:
    """Analyze artifacts for a phase. Return True if improvements logged."""
    artifacts_dir = body_root / ".bra" / "artifacts"
    work_dir = artifacts_dir / f"{phase}_work"
    if not work_dir.is_dir():
        return False

    hash_key = f"last_{phase}_hash"
    current_hash = _dir_hash(work_dir)
    last_hash = state.get(hash_key, "")

    if current_hash == last_hash and last_hash:
        return False

    improvements = ""

    if phase == "intel":
        target_enum = work_dir / "target_enumeration.md"
        if target_enum.is_file():
            text = _read_text(target_enum)
            targets = [line for line in text.splitlines() if re.search(r"\.apk|\.ipa|\.bin|\.img|\.rom", line)][:5]
            if targets:
                improvements += "**Target Types Found:**\n" + "\n".join(targets) + "\n\n"

        tool_avail = work_dir / "tool_availability.md"
        if tool_avail.is_file():
            text = _read_text(tool_avail)
            missing = [line for line in text.splitlines() if line.strip().startswith("[ ]")][:10]
            if missing:
                improvements += "**Tool Gaps Identified:**\n" + "\n".join(missing) + "\n"
                improvements += "*Proposal: Add missing tools to toolset.md*\n\n"

        scope_ver = work_dir / "scope_verification.md"
        if scope_ver.is_file():
            text = _read_text(scope_ver)
            if "WARNING: No scope.md" in text:
                improvements += "**Scope Gap:**\n- [ ] Create scope.md for this engagement\n\n"
            if "WARNING: No roe.md" in text:
                improvements += "**ROE Gap:**\n- [ ] Create roe.md (Rules of Engagement)\n\n"

    elif phase == "static":
        code_quality = work_dir / "code_quality.md"
        if code_quality.is_file():
            text = _read_text(code_quality)
            if re.search(r"password|secret|api_key|token", text, re.IGNORECASE):
                improvements += "**Hardcoded Secrets Found:**\n- [ ] Add secret detection patterns to methodology\n\n"
            todo_count = text.count("TODO") + text.count("FIXME")
            if todo_count > 0:
                improvements += f"**Code Quality:**\n- Found {todo_count} TODO/FIXME comments - potential incomplete features\n\n"

        dep_analysis = work_dir / "dependency_analysis.md"
        if dep_analysis.is_file():
            text = _read_text(dep_analysis)
            deps = [line for line in text.splitlines() if line.startswith("-")][:5]
            if deps:
                improvements += "**Dependencies:**\n" + "\n".join(deps) + "\n"
                improvements += "*Proposal: Run dependency vulnerability scan*\n\n"

        config_review = work_dir / "config_review.md"
        if config_review.is_file():
            text = _read_text(config_review)
            if ".env" in text:
                improvements += "**Environment Files Found:**\n- [ ] Review .env files for sensitive data exposure\n\n"

    elif phase == "dynamic":
        if (work_dir / "runtime_environment.md").is_file():
            improvements += "**Runtime Environment:**\n- Environment captured for reproducibility\n\n"
        readiness = work_dir / "dynamic_readiness.md"
        if readiness.is_file():
            text = _read_text(readiness)
            missing = [line for line in text.splitlines() if line.strip().startswith("[ ]")][:10]
            if missing:
                improvements += "**Dynamic Tool Gaps:**\n" + "\n".join(missing) + "\n"
                improvements += "*Proposal: Install missing dynamic analysis tools*\n\n"

        process_analysis = work_dir / "process_analysis.md"
        if process_analysis.is_file():
            text = _read_text(process_analysis)
            if "elevated permissions" in text:
                improvements += "**Permission Note:**\n- [ ] Some analysis requires elevated permissions\n\n"

    elif phase == "report":
        findings_summary = work_dir / "findings_summary.md"
        if findings_summary.is_file():
            text = _read_text(findings_summary)
            count = len(re.findall(r"^##", text, re.MULTILINE))
            if count > 0:
                improvements += f"**Findings Summary:**\n- {count} findings documented\n- [ ] Review for methodology improvements\n\n"

        pipeline_summary = work_dir / "pipeline_summary.md"
        if pipeline_summary.is_file():
            text = _read_text(pipeline_summary)
            phases_complete = text.count("[x]")
            if phases_complete > 0:
                improvements += f"**Phase Coverage:**\n- {phases_complete} phases completed\n"
                improvements += "*Proposal: Document effective phase sequence*\n\n"

    state[hash_key] = current_hash

    if improvements:
        section_name = f"{phase.title()} Phase"
        _append_to_section(improvements_file, section_name, improvements)
        state["pending_improvements"] = int(state.get("pending_improvements", 0)) + 1
        _append_log(log_file, "INFO", f"{phase} analysis: improvements logged")
        _maybe_generate_pitch(body_root, phase, improvements, state, pitches_dir, findings_text, leads_text)
        return True
    return False


# ============== FINDING/LEAD ANALYSIS ==============

def _count_findings(findings_file: Path) -> int:
    if not findings_file.is_file():
        return 0
    return len(FINDING_RE.findall(_read_text(findings_file)))


def _count_leads(leads_file: Path) -> int:
    if not leads_file.is_file():
        return 0
    return len(LEAD_RE.findall(_read_text(leads_file)))


def _get_latest_finding(findings_file: Path) -> str:
    """Extract the last finding section from FINDINGS.md."""
    if not findings_file.is_file():
        return ""
    text = _read_text(findings_file)
    sections = re.split(r"(?=^## \[FINDING-)", text, flags=re.MULTILINE)
    return sections[-1] if len(sections) > 1 else ""


def _analyze_finding(body_root: Path, state: dict, improvements_file: Path,
                     pitches_dir: Path, log_file: Path) -> int:
    findings_file = body_root / "layer3-engagement" / "NOTES" / "FINDINGS.md"
    if not findings_file.is_file():
        print("[SKIP] No FINDINGS.md found")
        return 2

    current_count = _count_findings(findings_file)
    previous = int(state.get("last_findings_count", 0))

    if current_count <= previous:
        print("[SKIP] No new findings since last analysis")
        return 2

    delta = current_count - previous
    latest = _get_latest_finding(findings_file)
    improvements = ""

    # Extract attack patterns
    patterns = _extract_attack_patterns(latest)
    if patterns:
        improvements += f"**Attack Pattern:**\n{patterns}\n\n"

    improvements += f"Added {delta} new finding-derived improvement candidate(s).\n"

    _append_to_section(improvements_file, "Finding-Derived", improvements)

    findings_text = _read_text(findings_file)
    leads_file = body_root / "layer3-engagement" / "NOTES" / "LEADS.md"
    leads_text = _read_text(leads_file)
    pitch = _maybe_generate_pitch(body_root, "finding", improvements, state, pitches_dir, findings_text, leads_text)

    state["last_findings_count"] = current_count
    state["pending_improvements"] = int(state.get("pending_improvements", 0)) + delta
    state["timestamp"] = _utc_now()

    _append_log(log_file, "INFO", f"Processed findings delta={delta}")
    if pitch:
        print(f"[+] Finding analysis complete ─ improvements logged")
        print(f"    Pitch: {pitch}")
    else:
        print(f"[+] Finding analysis complete ─ improvements logged ({delta} new)")
    return 0


def _analyze_lead(body_root: Path, state: dict, improvements_file: Path,
                  pitches_dir: Path, log_file: Path) -> int:
    leads_file = body_root / "layer3-engagement" / "NOTES" / "LEADS.md"
    if not leads_file.is_file():
        print("[SKIP] No LEADS.md found")
        return 2

    current_count = _count_leads(leads_file)
    previous = int(state.get("last_leads_count", 0))

    if current_count <= previous:
        print("[SKIP] No new leads since last analysis")
        return 2

    delta = current_count - previous
    leads_text = _read_text(leads_file)

    improvements = "**Attack Surface Ideas:**\n- Lead added: potential new attack vector\n"

    # Check for hypothesis patterns
    if re.search(r"hypothesis|theory|suspect", leads_text, re.IGNORECASE):
        improvements += "- [ ] Document hypothesis testing methodology\n"

    # Check for open status
    if re.search(r"OPEN|TODO|INVESTIGATE", leads_text, re.IGNORECASE):
        improvements += "- [ ] Follow up on open investigation lead\n"

    _append_to_section(improvements_file, "Lead-Derived", improvements)

    state["last_leads_count"] = current_count
    state["pending_improvements"] = int(state.get("pending_improvements", 0)) + delta
    state["timestamp"] = _utc_now()

    _append_log(log_file, "INFO", f"Processed leads delta={delta}")
    print(f"[+] Lead analysis complete ─ improvements logged ({delta} new)")
    return 0


# ============== OVERRIDE ANALYSIS ==============

def _analyze_overrides(body_root: Path, state: dict, pitches_dir: Path, log_file: Path) -> int:
    overrides_md = body_root / "layer3-engagement" / "OVERRIDES.md"
    overrides_log = body_root / ".bra" / "logs" / "overrides.log"

    text = ""
    if overrides_md.is_file():
        text = _read_text(overrides_md)
    elif overrides_log.is_file():
        text = _read_text(overrides_log)
    else:
        print("[SKIP] No override audit trail found")
        return 2

    if not text.strip():
        print("[SKIP] No override decisions recorded")
        return 2

    improvements = ""
    has_proposals = False

    # Count engagement-approved overrides
    engagement_matches = re.findall(r"APPROVED FOR ENGAGEMENT", text, re.IGNORECASE)
    if engagement_matches:
        improvements += f"**Engagement Override Proposals:**\n"
        improvements += f"- [ ] {len(engagement_matches)} engagement override(s) found — review for cross-engagement promotion\n\n"
        has_proposals = True

    # Count repeated one-time approvals
    once_matches = re.findall(r"APPROVED ONCE", text, re.IGNORECASE)
    if len(once_matches) >= 2:
        improvements += f"**Repeated One-Time Approvals:**\n"
        improvements += f"- [ ] {len(once_matches)} one-time approval(s) — recommend engagement override\n\n"
        has_proposals = True

    if has_proposals:
        counter = int(state.get("improvement_counter", 0)) + 1
        state["improvement_counter"] = counter
        _create_override_pitch(pitches_dir, improvements, counter)
        _append_log(log_file, "INFO", "Override analysis: pitch generated")
        print("[+] Override analysis complete ─ pitch generated")
    else:
        print("[IMPROVE] No actionable override patterns found")

    return 0


# ============== PROMOTION ==============

def _scan_checked_items(pitches_dir: Path) -> list[str]:
    items: list[str] = []
    if not pitches_dir.is_dir():
        return items
    for pitch in sorted(pitches_dir.glob("*.md")):
        for raw in _read_text(pitch).splitlines():
            line = raw.strip()
            if line.lower().startswith("- [x] ") and "PROMOTED" not in line:
                items.append(f"{pitch.name}: {line[6:].strip()}")
    return items


def _promote(body_root: Path, state: dict, improvements_file: Path,
             pitches_dir: Path, log_file: Path, dry_run: bool) -> int:
    checked = _scan_checked_items(pitches_dir)
    if not checked:
        print("[SKIP] No approved [x] items found in pitch documents")
        return 0

    print("[IMPROVE] Approved items:")
    for item in checked:
        print(f"  ─ {item}")

    if dry_run:
        print("[IMPROVE] Dry-run: no files modified")
        return 0

    _append_to_section(
        improvements_file,
        "Pending Review",
        "\n".join(f"- {_utc_now()} Promoted: {item}" for item in checked),
    )
    state["pending_improvements"] = 0
    _append_log(log_file, "INFO", f"Promoted {len(checked)} item(s)")
    print(f"[+] Promoted {len(checked)} item(s)")
    return 0


def _promote_overrides(body_root: Path, state: dict, pitches_dir: Path, log_file: Path) -> int:
    """Process override pitch decisions: approved → layer2 template, denied → delete."""
    override_pitches = sorted(pitches_dir.glob("*-override-recommendations-*.md"))
    if not override_pitches:
        print("[SKIP] No override recommendation pitch documents found")
        return 2

    promoted = 0
    denied_deleted = 0
    date_stamp = _today()

    for pitch_path in override_pitches:
        text = _read_text(pitch_path)
        lines = text.splitlines()
        new_lines = []
        changed = False

        for line in lines:
            if re.match(r"^- \[x\]", line) and "PROMOTED" not in line:
                new_lines.append(f"- [x] PROMOTED {date_stamp} - {line[6:]}")
                promoted += 1
                changed = True
            elif re.match(r"^- \[-\]", line):
                denied_deleted += 1
                changed = True
                continue  # delete denied lines
            else:
                new_lines.append(line)

        if changed:
            _safe_write_text(pitch_path, "\n".join(new_lines))

    _append_log(log_file, "INFO", f"Override promotion: promoted={promoted} denied={denied_deleted}")
    print("Override pitch processing complete.")
    print(f"  Files processed: {len(override_pitches)}")
    print(f"  Approved promoted: {promoted}")
    print(f"  Denied deleted: {denied_deleted}")
    return 0


