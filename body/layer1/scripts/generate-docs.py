#!/usr/bin/env python3
"""Generate CLI reference docs from @tags in .bats tests."""

from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path
from types import SimpleNamespace


TAGS = ("name", "category", "purpose", "args", "exit", "depends", "live-test")


def _body_root() -> Path:
    return Path(__file__).resolve().parents[2]


def _resolve_under_root(root: Path, raw: str) -> Path:
    candidate = Path(raw)
    if not candidate.is_absolute():
        candidate = root / candidate
    resolved = candidate.resolve(strict=False)
    try:
        resolved.relative_to(root.resolve(strict=False))
    except ValueError as exc:
        raise ValueError(f"Output path escapes body root: {raw}") from exc
    return resolved


def _parse_tags(path: Path) -> dict[str, str]:
    tags: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8", errors="ignore").splitlines():
        if not line.startswith("# @"):
            continue
        for tag in TAGS:
            prefix = f"# @{tag} "
            if line.startswith(prefix):
                tags[tag] = line[len(prefix) :].strip()
                break
    return tags


def _collect_components(tests_dir: Path, verbose: bool) -> list[dict[str, str]]:
    components: list[dict[str, str]] = []
    for bats in sorted(tests_dir.rglob("*.bats")):
        tags = _parse_tags(bats)
        if "name" not in tags:
            if verbose:
                print(f"[SKIP] no @name in {bats}")
            continue
        tags.setdefault("category", "other")
        tags["file"] = str(bats)
        components.append(tags)
        if verbose:
            print(f"[INFO] loaded {tags['name']} from {bats}")
    return components


def _capitalize(value: str) -> str:
    return value[:1].upper() + value[1:]


def _markdown(components: list[dict[str, str]], body_root: Path) -> str:
    grouped: dict[str, list[dict[str, str]]] = defaultdict(list)
    for component in components:
        grouped[component.get("category", "other")].append(component)

    categories = sorted(grouped.keys())
    lines = [
        "# CLI Reference",
        "",
        "> Auto-generated from test file @tags.",
        "> Run `python3 layer1/scripts/generate-docs.py` to regenerate.",
        "",
        "This reference documents all components tested in the BattleReadyDev framework.",
        "Each entry includes the component's purpose, arguments, exit codes, and dependencies.",
        "",
        "## Table of Contents",
        "",
    ]
    for category in categories:
        lines.append(f"- [{_capitalize(category)}](#{category})")

    lines.extend(["", "---", ""]) 

    for category in categories:
        lines.append(f"## {_capitalize(category)}")
        lines.append("")
        for entry in sorted(grouped[category], key=lambda item: item.get("name", "")):
            name = entry.get("name", "unknown")
            rel_file = Path(entry.get("file", "")).resolve(strict=False)
            try:
                rel_label = rel_file.relative_to(body_root.resolve(strict=False)).as_posix()
            except ValueError:
                rel_label = str(rel_file)

            lines.append(f"### `{name}`")
            lines.append("")
            if entry.get("purpose"):
                lines.append(f"**Purpose:** {entry['purpose']}")
                lines.append("")
            if entry.get("args") and entry["args"].lower() != "none":
                lines.extend(["**Arguments/Functions:**", "```", entry["args"], "```", ""])
            if entry.get("exit"):
                lines.append(f"**Exit Codes:** `{entry['exit']}`")
                lines.append("")
            if entry.get("depends") and entry["depends"].lower() != "none":
                lines.append(f"**Dependencies:** {entry['depends']}")
                lines.append("")
            if entry.get("live-test"):
                lines.extend(["**Live Test:**", "```bash", entry["live-test"], "```", ""])
            lines.append(f"**Test File:** [`{rel_label}`]({rel_label})")
            lines.extend(["", "---", ""])

    lines.extend(
        [
            "## Legend",
            "",
            "| Tag | Description |",
            "|-----|-------------|",
            "| `@name` | Component filename |",
            "| `@category` | Functional category |",
            "| `@purpose` | Brief description |",
            "| `@args` | Arguments or exported functions |",
            "| `@exit` | Exit codes and meanings |",
            "| `@depends` | Required dependencies |",
            "| `@live-test` | Command to manually verify |",
            "",
            "---",
            "",
            "*Generated by `layer1/scripts/generate-docs.py`*",
            "",
        ]
    )

    return "\n".join(lines)


_HELP_TEXT = """\
Usage: generate-docs.py [OPTIONS]

Extract @tags from test files and generate CLI-REFERENCE.md

OPTIONS:
    -h, --help      Show this help message
    -v, --verbose   Show verbose output
    -o, --output    Specify output file (default: layer2-templates/CLI-REFERENCE.md)
    --dry-run       Show what would be generated without writing

TAGS EXTRACTED:
    @name       - Component name (required for inclusion)
    @category   - Category (governance, hooks, lib, smoke, validation)
    @purpose    - Brief description of component purpose
    @args       - Arguments/functions the component accepts
    @exit       - Exit codes and their meanings
    @depends    - Dependencies on other components
    @live-test  - Example command to test the component

EXAMPLES:
    python3 layer1/scripts/generate-docs.py              # Generate CLI-REFERENCE.md
    python3 layer1/scripts/generate-docs.py --verbose    # Show progress
    python3 layer1/scripts/generate-docs.py --dry-run    # Preview without writing
"""


def _show_help() -> None:
    print(_HELP_TEXT.rstrip())


def _parse_args(argv: list[str]) -> SimpleNamespace:
    args = SimpleNamespace(verbose=False, output="layer2-templates/CLI-REFERENCE.md", dry_run=False, help=False, invalid="")
    index = 0
    while index < len(argv):
        raw = argv[index]
        if raw in {"-h", "--help"}:
            args.help = True
        elif raw in {"-v", "--verbose"}:
            args.verbose = True
        elif raw == "--dry-run":
            args.dry_run = True
        elif raw in {"-o", "--output"}:
            index += 1
            if index >= len(argv):
                args.invalid = raw
                return args
            args.output = argv[index]
        else:
            args.invalid = raw
            return args
        index += 1
    return args


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(sys.argv[1:] if argv is None else argv)
    if args.invalid:
        print(f"Unknown option: {args.invalid}", file=sys.stderr)
        _show_help()
        return 1
    if args.help:
        _show_help()
        return 0
    body_root = _body_root()
    tests_dir = body_root / "tests"

    if not tests_dir.is_dir():
        print(f"[ERROR] Tests directory not found: {tests_dir}", file=sys.stderr)
        return 1

    components = _collect_components(tests_dir, verbose=args.verbose)
    content = _markdown(components, body_root)

    if args.dry_run:
        print(content)
        print(f"[DRY-RUN] components={len(components)}")
        return 0

    try:
        output = _resolve_under_root(body_root, args.output)
    except ValueError as exc:
        print(f"[ERROR] {exc}", file=sys.stderr)
        return 1

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8")

    print(f"Generated {output}")
    print(f"Components: {len(components)}")
    print(f"Categories: {len({item.get('category', 'other') for item in components})}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
